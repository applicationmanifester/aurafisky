/**
 * @fileoverview Cross-Application Workflow Automation & RFC 5545 iCalendar (.ics) Generator
 * Aura of Sky Live (Aurafisky v19.0.0) — Module 6.7 Standards
 * 
 * Generates RFC 5545-compliant iCalendar files (.ics) for weather-optimized activity windows,
 * commute departure shifts, and field operations with Web Share API (navigator.share()) export.
 */

export class AuraWorkflowEngine {
  /**
   * Formats a Javascript Date or ISO string into UTC iCalendar format (YYYYMMDDTHHMMSSZ)
   * @param {Date | string} date 
   * @returns {string}
   */
  static formatIcsDate(date) {
    const d = typeof date === 'string' ? new Date(date) : date;
    return d.toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';
  }

  /**
   * Generates standard RFC 5545 .ics text for a weather event window
   * 
   * @param {Object} event
   * @param {string} event.title Event summary
   * @param {string} [event.description] Detailed weather description / advice
   * @param {Date | string} event.startTime Event start
   * @param {Date | string} event.endTime Event end
   * @param {string} [event.location] Location name or coordinates
   * @param {number} [event.lat] Latitude
   * @param {number} [event.lng] Longitude
   * @param {string} [event.url] Link to route or weather map
   * @returns {string} RFC 5545 formatted .ics calendar string
   */
  static generateIcs(event) {
    const dtStamp = AuraWorkflowEngine.formatIcsDate(new Date());
    const dtStart = AuraWorkflowEngine.formatIcsDate(event.startTime);
    const dtEnd = AuraWorkflowEngine.formatIcsDate(event.endTime);
    const uid = `aurafisky-${Date.now()}-${Math.random().toString(36).slice(2, 9)}@aurafisky.web.app`;

    const summary = (event.title || 'Aurafisky Weather Window').replace(/\n/g, ' ');
    const desc = (event.description || 'Optimized outdoor weather window generated by Aura AI').replace(/\n/g, '\\n');
    const loc = (event.location || '').replace(/\n/g, ' ');

    let geoLine = '';
    if (event.lat != null && event.lng != null) {
      geoLine = `GEO:${event.lat.toFixed(6)};${event.lng.toFixed(6)}\r\n`;
    }

    let urlLine = '';
    if (event.url) {
      urlLine = `URL:${event.url}\r\n`;
    }

    return [
      'BEGIN:VCALENDAR',
      'VERSION:2.0',
      'PRODID:-//Aura of Sky Live//Aurafisky v19.0.0//EN',
      'CALSCALE:GREGORIAN',
      'METHOD:PUBLISH',
      'BEGIN:VEVENT',
      `UID:${uid}`,
      `DTSTAMP:${dtStamp}`,
      `DTSTART:${dtStart}`,
      `DTEND:${dtEnd}`,
      `SUMMARY:${summary}`,
      `DESCRIPTION:${desc}`,
      loc ? `LOCATION:${loc}` : '',
      geoLine.trim(),
      urlLine.trim(),
      'STATUS:CONFIRMED',
      'BEGIN:VALARM',
      'TRIGGER:-PT30M',
      'ACTION:DISPLAY',
      `DESCRIPTION:Reminder: ${summary}`,
      'END:VALARM',
      'END:VEVENT',
      'END:VCALENDAR',
    ]
      .filter(Boolean)
      .join('\r\n');
  }

  /**
   * Shares the generated .ics file via Web Share API or triggers local file download
   * 
   * @param {Object} event Event details passed to generateIcs()
   * @returns {Promise<boolean>} Success status
   */
  static async exportToCalendar(event) {
    const icsContent = AuraWorkflowEngine.generateIcs(event);
    const filename = `${(event.title || 'weather-window').toLowerCase().replace(/[^a-z0-9]/g, '-')}.ics`;
    const blob = new Blob([icsContent], { type: 'text/calendar;charset=utf-8' });

    // 1. Try Web Share API with File
    if (typeof navigator !== 'undefined' && navigator.canShare && navigator.share) {
      try {
        const file = new File([blob], filename, { type: 'text/calendar' });
        if (navigator.canShare({ files: [file] })) {
          await navigator.share({
            title: event.title || 'Aurafisky Weather Event',
            text: event.description || '',
            files: [file],
          });
          return true;
        }
      } catch (_) {}
    }

    // 2. Fallback: Browser direct download
    if (typeof document !== 'undefined') {
      try {
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = filename;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        setTimeout(() => URL.revokeObjectURL(url), 1000);
        return true;
      } catch (_) {}
    }

    return false;
  }
}

