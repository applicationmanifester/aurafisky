// ── Locale detection & preferences ─────────────────────────────────

export function detectLocale() {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored && SUPPORTED.includes(stored)) return stored;
  } catch {
    /* ignore */
  }
  try {
    const nav = (navigator.language || navigator.userLanguage || "en").toLowerCase();
    if (SUPPORTED.includes(nav)) return nav;
    const primary = nav.split(/[-_]/)[0];
    if (SUPPORTED.includes(primary)) return primary;
  } catch {
    /* ignore */
  }
  return DEFAULT;
}

export function setLocale(locale) {
  if (!locale) return false;
  if (!SUPPORTED.includes(locale)) return false;
  try {
    localStorage.setItem(LANG_KEY, locale);
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    /* ignore */
  }
  return true;
}

export function supportedLocales() {
  return [...SUPPORTED];
}

export function isSupported(locale) {
  return SUPPORTED.includes(locale);
}

// ── Translation Engine ─────────────────────────────────────────────

export function t(key, locale = detectLocale()) {
  if (!key) return "";
  const dict = DICT[locale] || DICT[DEFAULT];
  if (dict && Object.prototype.hasOwnProperty.call(dict, key)) {
    return dict[key];
  }
  const fallback = DICT[DEFAULT];
  if (fallback && Object.prototype.hasOwnProperty.call(fallback, key)) {
    return fallback[key];
  }
  // Check in phrase map if key is an exact English phrase
  const phrases = PHRASES[locale];
  if (phrases && phrases[key]) {
    return phrases[key];
  }
  return key;
}

export function tf(key, vars = {}, locale = detectLocale()) {
  let str = t(key, locale);
  for (const [k, v] of Object.entries(vars)) {
    str = str.replace(new RegExp(`{{${k}}}`, "g"), String(v));
  }
  return str;
}

/**
 * Universal text translation for any string in the UI.
 * Handles direct dictionary matches, phrase lookups, and regex patterns.
 */
export function translateText(rawText, locale = detectLocale()) {
  if (!rawText || typeof rawText !== "string") return rawText;
  if (!locale || locale === "en") return rawText;

  const trimmed = rawText.trim();
  if (!trimmed) return rawText;

  // 1. Direct phrase lookup
  const pMap = PHRASES[locale] || {};
  if (pMap[trimmed]) {
    return rawText.replace(trimmed, pMap[trimmed]);
  }

  // Trailing ellipsis handler
  if (trimmed.endsWith("...") || trimmed.endsWith("…")) {
    const withoutDots = trimmed.replace(/\.{3}$|…$/, "").trim();
    if (pMap[withoutDots]) {
      const suffix = trimmed.endsWith("…") ? "…" : "...";
      return rawText.replace(trimmed, pMap[withoutDots] + suffix);
    }
  }

  // 2. Direct dictionary key check
  const fromT = t(trimmed, locale);
  if (fromT && fromT !== trimmed) {
    return rawText.replace(trimmed, fromT);
  }

  // 3. Dynamic patterns
  // Pattern: Show All (N)
  const showAllMatch = trimmed.match(/^Show All\s*\((\d+)\)$/i);
  if (showAllMatch) {
    const showAllTrans = pMap["Show All"] || t("show_all", locale) || "Show All";
    return rawText.replace(trimmed, `${showAllTrans} (${showAllMatch[1]})`);
  }

  // Pattern: Stop N
  const stopMatch = trimmed.match(/^Stop\s*(\d+)$/i);
  if (stopMatch) {
    const stopTrans = pMap["Stop"] || t("stop", locale) || "Stop";
    return rawText.replace(trimmed, `${stopTrans} ${stopMatch[1]}`);
  }

  // Pattern: Stops (N)
  const stopsMatch = trimmed.match(/^Stops\s*\((\d+)\)$/i);
  if (stopsMatch) {
    const stopsTrans = pMap["Stops"] || t("stops", locale) || "Stops";
    return rawText.replace(trimmed, `${stopsTrans} (${stopsMatch[1]})`);
  }

  // Pattern: Next rain TIME
  const nextRainMatch = trimmed.match(/^(?:🌧️\s*)?Next rain\s+(.+)$/i);
  if (nextRainMatch) {
    const nextRainTrans = pMap["Next rain"] || t("next_rain", locale) || "Next rain";
    return rawText.replace(trimmed, `🌧️ ${nextRainTrans} ${nextRainMatch[1]}`);
  }

  // Pattern: Tailwind / Headwind / Crosswind (+N km/h)
  const windMatch = trimmed.match(/^(Tailwind|Headwind|Crosswind)\s*\(([^)]+)\)$/i);
  if (windMatch) {
    const windTrans = pMap[windMatch[1]] || windMatch[1];
    return rawText.replace(trimmed, `${windTrans} (${windMatch[2]})`);
  }

  // Pattern: N% trust (temp T%, wind W%, precip P%)
  const trustMatch = trimmed.match(/^(?:🎯\s*)?(\d+)%\s*trust\s*\(temp\s*(\d+)%,\s*wind\s*(\d+)%,\s*precip\s*(\d+)%\)$/i);
  if (trustMatch) {
    if (locale === "kn") {
      return rawText.replace(trimmed, `🎯 ${trustMatch[1]}% ವಿಶ್ವಾಸಾರ್ಹತೆ (ತಾಪ ${trustMatch[2]}%, ಗಾಳಿ ${trustMatch[3]}%, ಮಳೆ ${trustMatch[4]}%)`);
    } else if (locale === "hi") {
      return rawText.replace(trimmed, `🎯 ${trustMatch[1]}% विश्वसनीयता (ताप ${trustMatch[2]}%, हवा ${trustMatch[3]}%, वर्षा ${trustMatch[4]}%)`);
    } else if (locale === "ta") {
      return rawText.replace(trimmed, `🎯 ${trustMatch[1]}% நம்பகத்தன்மை (வெப்பம் ${trustMatch[2]}%, காற்று ${trustMatch[3]}%, மழை ${trustMatch[4]}%)`);
    } else if (locale === "te") {
      return rawText.replace(trimmed, `🎯 ${trustMatch[1]}% విశ్వసనీయత (ఉష్ణోగ్రత ${trustMatch[2]}%, గాలి ${trustMatch[3]}%, వర్షం ${trustMatch[4]}%)`);
    } else if (locale === "es") {
      return rawText.replace(trimmed, `🎯 ${trustMatch[1]}% confianza (temp ${trustMatch[2]}%, viento ${trustMatch[3]}%, precip ${trustMatch[4]}%)`);
    }
  }

  // Pattern: arriving in ~Nh from the DIR
  const arriveMatch = trimmed.match(/arriving in ~(\d+)h from the ([A-Z]+)/i);
  if (arriveMatch) {
    const hours = arriveMatch[1];
    const dir = arriveMatch[2];
    if (locale === "kn") {
      return rawText.replace(arriveMatch[0], `~${hours} ಗಂಟೆಯಲ್ಲಿ ${dir} ನಿಂದ ಬರುತ್ತಿದೆ`);
    } else if (locale === "hi") {
      return rawText.replace(arriveMatch[0], `~${hours} घंटे में ${dir} से आ रहा है`);
    } else if (locale === "ta") {
      return rawText.replace(arriveMatch[0], `~${hours} மணிநேரத்தில் ${dir} இலிருந்து வருகிறது`);
    } else if (locale === "te") {
      return rawText.replace(arriveMatch[0], `~${hours} గంటల్లో ${dir} నుండి వస్తోంది`);
    }
  }

  // Pattern: LIVE WEATHER INTELLIGENCE • CITY
  const lwiMatch = trimmed.match(/^LIVE WEATHER INTELLIGENCE\s*•\s*(.+)$/i);
  if (lwiMatch) {
    const lwiTrans = pMap["Live Weather Intelligence"] || "Live Weather Intelligence";
    return rawText.replace(trimmed, `${lwiTrans.toUpperCase()} • ${lwiMatch[1]}`);
  }

  // Pattern: ... limiting comfort
  if (trimmed.includes("limiting comfort")) {
    const comfortTrans = pMap["limiting comfort"] || "limiting comfort";
    let res = rawText.replace("limiting comfort", comfortTrans);
    ["Temperature", "Humidity", "Wind", "Air Quality", "Precipitation", "Cloud Cover", "UV"].forEach(param => {
      if (pMap[param]) res = res.replace(new RegExp(`\\b${param}\\b`, "g"), pMap[param]);
    });
    return res;
  }

  return rawText;
}

/**
 * Recursively translates all visible text nodes, placeholders, titles, and
 * aria-labels within a DOM element tree.
 */
export function translateDOM(root = (typeof document !== "undefined" ? document.body : null), locale = detectLocale()) {
  if (!root || typeof document === "undefined") return;
  if (!locale) locale = detectLocale();

  // 1. Direct explicit translations for known key UI targets
  const copyBtn = root.querySelector ? root.querySelector("#copyAddressBtnText") : document.getElementById("copyAddressBtnText");
  if (copyBtn) copyBtn.textContent = t("copy", locale) || "Copy";

  const detailsBtn = root.querySelector ? root.querySelector("#toggleAddressCardText") : document.getElementById("toggleAddressCardText");
  if (detailsBtn) detailsBtn.textContent = t("details", locale) || "Details";

  const briefingBtn = root.querySelector ? root.querySelector("#briefingBtn") : document.getElementById("briefingBtn");
  if (briefingBtn) briefingBtn.textContent = `📡 ${t("generate_briefing", locale) || "Generate Briefing"}`;

  const discHeader = root.querySelector ? root.querySelector("#discoveriesHeaderTitle") : document.getElementById("discoveriesHeaderTitle");
  if (discHeader) discHeader.textContent = t("live_weather_intelligence_safety", locale) || "Live Weather Intelligence & Safety";

  // 2. TreeWalker for all text nodes
  try {
    const walker = document.createTreeWalker(
      root,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode(node) {
          if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
          const parent = node.parentElement;
          if (!parent) return NodeFilter.FILTER_REJECT;
          const tag = parent.tagName.toLowerCase();
          if (tag === "script" || tag === "style" || tag === "textarea" || tag === "code" || tag === "pre") {
            return NodeFilter.FILTER_REJECT;
          }
          if (parent.closest && (parent.closest("#settingsAppLanguageSelect") || parent.classList?.contains("notranslate"))) {
            return NodeFilter.FILTER_REJECT;
          }
          return NodeFilter.FILTER_ACCEPT;
        }
      }
    );

    const textNodes = [];
    while (walker.nextNode()) {
      textNodes.push(walker.currentNode);
    }

    for (const node of textNodes) {
      const parent = node.parentElement;
      const orig = parent?.getAttribute("data-orig-text") || node.nodeValue;
      if (parent && !parent.hasAttribute("data-orig-text")) {
        parent.setAttribute("data-orig-text", orig);
      }
      const translated = translateText(orig, locale);
      if (translated && translated !== orig) {
        node.nodeValue = translated;
      } else if (locale === "en" && orig) {
        node.nodeValue = orig;
      }
    }
  } catch (err) {
    /* ignore tree walker error */
  }

  // 3. Attributes: placeholder, title, aria-label
  try {
    const attrElements = root.querySelectorAll ? root.querySelectorAll("[placeholder], [title], [aria-label]") : [];
    attrElements.forEach(el => {
      if (el.id === "settingsAppLanguageSelect") return;
      ["placeholder", "title", "aria-label"].forEach(attr => {
        const val = el.getAttribute(attr);
        if (val && val.trim()) {
          const origKey = `data-orig-${attr}`;
          const origVal = el.getAttribute(origKey) || val;
          if (!el.hasAttribute(origKey)) el.setAttribute(origKey, origVal);
          const transVal = translateText(origVal, locale);
          if (transVal && transVal !== origVal) {
            el.setAttribute(attr, transVal);
          } else if (locale === "en") {
            el.setAttribute(attr, origVal);
          }
        }
      });
    });
  } catch (_) {}
}

