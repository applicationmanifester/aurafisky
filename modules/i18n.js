// ── Internationalisation ────────────────────────────────────────────
//
// Aurafisky's audience is global, and the Aura assistant in particular has
// to work in the language the user thinks in. The previous state was a single
// hard-coded English string set with no translation hook at all.
//
// Design:
//   * A tiny key/value dictionary per locale, with English as the fallback
//     for any key a locale has not translated yet. Missing keys never throw,
//     they just return the key itself (so a missing translation is visible
//     rather than silent).
//   * Locale detection from navigator.language, with a manual override stored
//     in localStorage and synced to Firestore (preferences.mapLanguage was
//     already wired; we extend it to a real language preference).
//   * Aura's intent classifier gets per-locale keyword sets, so "barish",
//     "lluvia", "pluie" all route to the rain intent without each answer
//     being translated by hand.
//
// Coverage today: EN, HI (Hinglish), ES, FR, DE. The UI strings are the
// high-traffic ones (header, panel, Aura, wallpaper, settings, alerts). The
// long-form copy (privacy policy, terms) stays English until counsel reviews.

