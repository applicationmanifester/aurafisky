// ── Locale detection ───────────────────────────────────────────────

const LANG_KEY = "aurafisky_lang";

export function detectLocale() {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored && SUPPORTED.includes(stored)) return stored;
  } catch {
    /* ignore */
  }
  try {
    const nav = (navigator.language || navigator.userLanguage || "en").toLowerCase();
    const primary = nav.split(/[-_]/)[0];
    if (SUPPORTED.includes(primary)) return primary;
  } catch {
    /* ignore */
  }
  return DEFAULT;
}

export function setLocale(locale) {
  if (!SUPPORTED.includes(locale)) return false;
  try {
    localStorage.setItem(LANG_KEY, locale);
  } catch {
    /* ignore */
  }
  return true;
}

export function supportedLocales() {
  return [...SUPPORTED];
}

export function isSupported(locale) {
  return SUPPORTED.includes(locale);
}

// ── Translation ────────────────────────────────────────────────────

/**
 * Translate a key. Returns the translated string, or the key itself if no
 * translation exists (so missing translations are visible rather than
 * silently falling back to English).
 */
export function t(key, locale = detectLocale()) {
  if (!key) return "";
  const dict = DICT[locale] || DICT[DEFAULT];
  if (dict && Object.prototype.hasOwnProperty.call(dict, key)) {
    return dict[key];
  }
  // Fall back to English for any missing key.
  const fallback = DICT[DEFAULT];
  if (fallback && Object.prototype.hasOwnProperty.call(fallback, key)) {
    return fallback[key];
  }
  return key;
}

/**
 * Translate with interpolation. Placeholders are {{name}}.
 */
export function tf(key, vars = {}, locale = detectLocale()) {
  let str = t(key, locale);
  for (const [k, v] of Object.entries(vars)) {
    str = str.replace(new RegExp(`{{${k}}}`, "g"), String(v));
  }
  return str;
}

