// Generates one module per language from the two dictionary data files.
//
// The dictionaries used to be a single 609 KB object that every visitor
// downloaded before the app could start — for the one language they read.
// Splitting them per language puts ~10-22 KB on the critical path instead.
//
// Usage: node scripts/split-i18n-locales.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..");

const { ALL_DICTIONARIES } = await import(pathToFileURL(join(repo, "modules/i18n-data.js")).href);
const { COMPREHENSIVE_TRANSLATIONS } = await import(pathToFileURL(join(repo, "modules/i18n-extended.js")).href);

const outDir = join(repo, "modules/i18n-locales");
mkdirSync(outDir, { recursive: true });

const languages = Object.keys(ALL_DICTIONARIES);

// The comprehensive translations are keyed by English phrase and hold every
// language, so each language's file takes the slice that belongs to it.
const perLanguageComprehensive = {};
for (const lang of languages) perLanguageComprehensive[lang] = {};
for (const [key, langMap] of Object.entries(COMPREHENSIVE_TRANSLATIONS)) {
  for (const [lang, text] of Object.entries(langMap || {})) {
    if (!perLanguageComprehensive[lang]) perLanguageComprehensive[lang] = {};
    perLanguageComprehensive[lang][key] = { [lang]: text };
  }
}

const banner = `// Generated by scripts/split-i18n-locales.mjs — do not edit by hand.
// Source: modules/i18n-data.js + modules/i18n-extended.js
`;

let total = 0;
for (const lang of languages) {
  const dictionary = ALL_DICTIONARIES[lang] || {};
  const comprehensive = perLanguageComprehensive[lang] || {};
  const body =
    `${banner}\n` +
    `export const DICTIONARY = ${JSON.stringify(dictionary, null, 0)};\n\n` +
    `export const COMPREHENSIVE = ${JSON.stringify(comprehensive, null, 0)};\n`;
  const file = join(outDir, `${lang}.js`);
  writeFileSync(file, body, "utf8");
  total += Buffer.byteLength(body);
}

// The loader map. Each entry is its own chunk, so a visitor downloads only
// the language they read.
const entries = languages
  .map((lang) => `  ${JSON.stringify(lang)}: () => import("./${lang}.js"),`)
  .join("\n");
writeFileSync(
  join(outDir, "index.js"),
  `${banner}\n// One chunk per language. The map of loaders is tiny; the chunks it\n// points at are fetched only when that language is needed.\nexport const LOCALE_LOADERS = {\n${entries}\n};\n`,
  "utf8",
);

console.log(`wrote ${languages.length} locale modules to ${outDir}`);
console.log(`total ${Math.round(total / 1024)} KB across all languages`);
console.log(
  `largest: ${languages
    .map((l) => [l, Buffer.byteLength(JSON.stringify(ALL_DICTIONARIES[l] || {}))])
    .sort((a, b) => b[1] - a[1])[0][0]} ` +
    `${Math.round(
      languages
        .map((l) => Buffer.byteLength(JSON.stringify(ALL_DICTIONARIES[l] || {})))
        .sort((a, b) => b - a)[0] / 1024,
    )} KB`,
);
